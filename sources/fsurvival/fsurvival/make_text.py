#!/usr/bin/env python3
"""Build the FSurvival text blob from content.py (the FGuide layout).

Layout (all lengths are bytes):
  N x { u16 offset, u8 line_count }            section table
  per section at its offset:
    u8 n, home label    u8 n, page title    line_count x { u8 n, line }
Entries read "KEY: TEXT", or TEXT alone indented under the previous key,
wrapped to LINE_CHARS (5x5 font, 6 px per glyph); continuation lines are
indented by INDENT spaces. The first ASSET_MAX bytes go to the app assets,
the rest to text_tail.h (code rodata), with the section count and the
section opened by MENU and the interface strings (UI_*).
"""
import importlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
# The language is the 4th argument: content.py (en) or content_<lang>.py.
LANG = sys.argv[4] if len(sys.argv) > 4 and not sys.argv[4].startswith('-') else 'en'
content = importlib.import_module('content' if LANG == 'en' else 'content_' + LANG)
SECTIONS, MENU, UI = content.SECTIONS, content.MENU, content.UI

LINE_CHARS = 21   # x 0..124, the scroll bar at 126..127
INDENT = 2
TITLE_CHARS = 14  # bold title, 7 px per glyph, beside the battery percent
HOME_CHARS = 17   # after the section number
ALLOWED = set(' !"#$%&\'()*+,-./0123456789:;<=>?ABCDEFGHIJKLMNOPQRSTUVWXYZ[]_')


def entry_lines(key, desc):
    words = (key + (': ' + desc if desc else '') if key else desc).split()
    lines, line = [], '' if key else ' ' * INDENT
    for word in words:
        assert len(word) <= LINE_CHARS - INDENT, word
        if line.strip() and len(line) + 1 + len(word) > LINE_CHARS:
            lines.append(line)
            line = ' ' * INDENT + word
        else:
            line = (line + ' ' + word) if line.strip() else line + word
    lines.append(line)
    return lines


def section_lines(rows):
    out = []
    for key, desc in rows:
        assert set(key) <= ALLOWED and set(desc) <= ALLOWED, (key, desc)
        out += entry_lines(key, desc)
    return out


def field(s):
    b = s.encode('ascii')
    assert len(b) < 64
    return bytes([len(b)]) + b


def build():
    assert len(SECTIONS) <= 20
    table, body = b'', b''
    base = 3 * len(SECTIONS)
    for home, title, rows in SECTIONS:
        assert len(title) <= TITLE_CHARS and len(home) <= HOME_CHARS, (home, title)
        lines = section_lines(rows)
        table += (base + len(body)).to_bytes(2, 'little') + bytes([len(lines)])
        body += field(home) + field(title)
        for line in lines:
            body += field(line)
    return table + body


if __name__ == '__main__':
    blob = build()
    asset_max = int(sys.argv[3]) if len(sys.argv) > 3 else 0xF00
    head, tail = blob[:asset_max], blob[asset_max:]
    Path(sys.argv[1]).write_bytes(head)
    with open(sys.argv[2], 'w') as f:
        f.write('/* Generated by make_text.py: text past the asset area. */\n')
        f.write('#define TEXT_ASSET_SIZE %du\n#define TEXT_SIZE %du\n' % (len(head), len(blob)))
        f.write('#define TEXT_SECTIONS %du\n#define TEXT_MENU %du\n' % (len(SECTIONS), MENU))
        for key, text in UI.items():
            assert set(text) <= ALLOWED and len(text) <= LINE_CHARS, text
            f.write('#define UI_%s "%s"\n' % (key, text))
        f.write('static const uint8_t text_tail[%d] = {' % max(len(tail), 1))
        f.write(','.join(str(b) for b in tail) if tail else '0')
        f.write('};\n')
    print('text %d B: assets %d B, code %d B' % (len(blob), len(head), len(tail)))
    if '--dump' in sys.argv:
        for home, title, rows in SECTIONS:
            print('==', title)
            print('\n'.join(section_lines(rows)))
