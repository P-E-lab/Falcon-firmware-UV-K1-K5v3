/* Modified for Falcon ("POCSAG Scan"): scan of the memory channels of the
 * scan list named POCSAG, frequency of each page, key 5 hold. A channel whose
 * REG_65 noise shows no carrier at one of three reads, 20, 40 and 60 ms after
 * the tune, and where no preamble was heard, is left at once (the slots for
 * the keys and the screen wait for the next tune, not to cut that listening); one with a carrier is kept while it lasts. A
 * carrier: the noise NOISE_DROP below the one each channel shows without a
 * carrier (learnt as it scans), or under NOISE_OPEN; a weak one (the drop
 * only) keeps it 0.6 s, longer only if a preamble or a batch is read. Key 3
 * shows the 1200-baud counters. The 512-baud lane is removed (room
 * for the scan; 512-baud preambles are still told, key 3), so the text below
 * on 512 bauds is Armel's, not this app's. The screen is redrawn twice a
 * second while scanning, not at each hop. Everything else is Armel's POCSAG
 * RX unchanged. Bottom line: the memory channel's name of the page; key 0
 * in HOLD: the next channel. */

/*
 * POCSAG RX - receives POCSAG pager transmissions at 1200 bauds (as the
 * amateur DAPNET network sends them) and at 512 bauds, both at once, in
 * software, and keeps the last ten pages, shown one at a time: address (RIC),
 * text, function. The rate of each preamble heard (512, 1200 or 2400, the
 * last not decoded) is shown with key 3. Tune the VFO (FM; 439.9875 MHz for
 * DAPNET, or 433.650 MHz for the Flipper Zero bench files of
 * test/flipper_pocsag.py), then launch.
 *
 * POCSAG keys the carrier frequency with the bits themselves: the discriminator
 * outputs the NRZ bit stream, not tones. The receiver is switched to RAW (RX
 * HPF300 / LPF3K / de-emphasis and AFC off, as EPIRB 406) and the audio is read
 * as APRS RX does: PA4 held at mid-scale by the MCU DAC, ADC channel 4 at
 * 9.6 kHz, timed from SysTick, continuously. Each sample goes through the
 * demodulator modelled and tested in test/model_rx.py: two lanes, 1200 and
 * 512 bauds, each a box filter of about half a bit then 3 hysteresis
 * slicers. The audio path cuts the low frequencies, so a
 * run of equal bits droops back to zero and a slicer comparing the level with
 * a threshold reads noise there (the first build did, and found nothing): each
 * slicer flips its level on the pulse a change of bit leaves and holds in
 * between, at 1/4, 3/8 and 1/2 of the peak. Each has its DPLL, the sync
 * codeword in either polarity, the BCH check with one bit corrected, and the
 * page assembly. Keep the two in step.
 * Keys and the screen cost sample time: they are served every 50 ms while no
 * slicer is inside a batch, and during the sync codeword of each batch
 * otherwise (twice a second), where no page bit is lost; the bit clocks are
 * run over the samples not taken, so the codeword alignment survives. The
 * redraw follows a new page, a key, or every 5 s. A new page also blinks the
 * green LED twice (0.4 s): a GPIO write, no sample lost.
 * A codeword that cannot be corrected does not end a page: its characters are
 * marked '?' and filled from another slicer's copy when one read them.
 *
 * Keys (UV-K5 and UV-K1): UP/DOWN scroll the text a row when it overflows;
 *   pressed again at either end: the newer / older page · * normal view /
 *   compact view (saved) · 1 speaker on/off (saved, off by default; not gated
 *   by the squelch: the receiver's hiss is heard) · 2 clear · 3 bottom line:
 *   level and age of the page / preamble rate and what each lane reads ·
 *   EXIT quit.
 * The loader re-runs RADIO_SetupRegisters on exit; the resident capture
 * (af_capture_close) restores the ADC, PA4, the DAC and its clock.
 */

