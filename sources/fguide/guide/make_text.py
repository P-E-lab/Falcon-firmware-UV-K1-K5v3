#!/usr/bin/env python3
"""Build the FGuide text blob from content.py.

Layout (all lengths are bytes):
  10 x { u16 offset, u8 line_count }            section table
  per section at its offset:
    u8 n, home label    u8 n, page title    line_count x { u8 n, line }
Entries read "KEY: DESCRIPTION" as in the Keys Infos popups, wrapped here to
LINE_CHARS (5x5 font, 6 px per glyph); continuation lines are indented by
INDENT spaces. The first ASSET_MAX bytes go to the app assets, the rest to
text_tail.h (code rodata).
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from content import SECTIONS  # noqa: E402

LINE_CHARS = 21   # x 0..124, the scroll bar at 126..127
INDENT = 2
TITLE_CHARS = 14  # bold title, 7 px per glyph, beside the battery percent
HOME_CHARS = 17   # after the section number
ALLOWED = set(' !"#$%&\'()*+,-./0123456789:;<=>?ABCDEFGHIJKLMNOPQRSTUVWXYZ[]_')


def entry_lines(key, desc):
    words = (key + (': ' + desc if desc else '')).split()
    lines, line, width = [], '', LINE_CHARS
    for word in words:
        assert len(word) <= LINE_CHARS - INDENT, word
        if line and len(line) + 1 + len(word) > width:
            lines.append(line)
            line, width = ' ' * INDENT + word, LINE_CHARS
        else:
            line = (line + ' ' + word) if line else word
    lines.append(line)
    return lines


def section_lines(rows):
    out = []
    for key, desc in rows:
        assert set(key) <= ALLOWED and set(desc) <= ALLOWED, (key, desc)
        out += entry_lines(key, desc)
    return out


def field(s):
    b = s.encode('ascii')
    assert len(b) < 64
    return bytes([len(b)]) + b


def build():
    assert len(SECTIONS) == 10
    table, body = b'', b''
    base = 3 * len(SECTIONS)
    for home, title, rows in SECTIONS:
        assert len(title) <= TITLE_CHARS and len(home) <= HOME_CHARS, (home, title)
        lines = section_lines(rows)
        table += (base + len(body)).to_bytes(2, 'little') + bytes([len(lines)])
        body += field(home) + field(title)
        for line in lines:
            body += field(line)
    return table + body


if __name__ == '__main__':
    blob = build()
    asset_max = int(sys.argv[3]) if len(sys.argv) > 3 else 0xF00
    head, tail = blob[:asset_max], blob[asset_max:]
    Path(sys.argv[1]).write_bytes(head)
    with open(sys.argv[2], 'w') as f:
        f.write('/* Generated by make_text.py: text past the asset area. */\n')
        f.write('#define TEXT_ASSET_SIZE %du\n#define TEXT_SIZE %du\n' % (len(head), len(blob)))
        f.write('static const uint8_t text_tail[%d] = {' % max(len(tail), 1))
        f.write(','.join(str(b) for b in tail) if tail else '0')
        f.write('};\n')
    print('text %d B: assets %d B, code %d B' % (len(blob), len(head), len(tail)))
    if '--dump' in sys.argv:
        for home, title, rows in SECTIONS:
            print('==', title)
            print('\n'.join(section_lines(rows)))
